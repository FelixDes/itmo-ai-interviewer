-- Режим оценки выбирается на вакансии:
--   RULES — вердикты и балл считают правила, модель пишет только текст;
--   LLM   — модель решает всё сама.
-- Режим записывается в карточку, чтобы прогоны можно было сравнивать.
alter table vacancy
    add column evaluation_mode varchar(20) not null default 'RULES';
